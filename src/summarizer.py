# свёртка переписки сессии в сводку.
# порядок: проверка объёма сессии либо разбор прямой просьбы пользователя ->
# сборка стенограммы переписки с указанием авторов -> запрос на суммаризацию
# к той же модели -> запись сводки в таблицу summaries -> новый контекст
# сессии, состоящий из одной сводки.
# вход: контекст сессии от storage.get_history и текст текущего письма.
# выход: текст сводки и строка контекста в форме реплики истории.
# SESSION_MAX_CHARS, SUMMARY_COMPRESSION_RATIO, SUMMARY_ENABLED
# и MAIL_DISPLAY_NAME импортируются из config.py, запрос выполняет llm.py,
# запись — storage.py.
# вызывается из pipeline.py перед обращением к модели.
#
# сводка нужна потому, что переписка треда растёт без предела, а окно модели
# конечно. свёртка заменяет реплики одной строкой и переносит границу контекста
# вперёд: письма до неё в запрос больше не попадают ни из базы (storage
# отбирает их по covers_upto), ни из цитаты в новом письме (её снимает
# email_parser, а модель получает указание в шапке сводки — llm.SUMMARY_PREFIX)

import logging
import re
from typing import Any, Dict, List, Optional, Sequence

from src import llm, storage
from src.config import (
    MAIL_DISPLAY_NAME,
    SESSION_MAX_CHARS,
    SUMMARY_COMPRESSION_RATIO,
    SUMMARY_ENABLED,
)
from src.email_parser import REPLY_MARKER
from src.storage import SUMMARY_ROLE

log = logging.getLogger(__name__)

# причины свёртки, попадают в колонку summaries.reason
REASON_LIMIT = "limit"
REASON_REQUEST = "request"

# нижняя граница объёма сводки в символах. доля SUMMARY_COMPRESSION_RATIO
# от короткой переписки даёт несколько десятков знаков, в которые не помещается
# ни один вопрос с ответом
MIN_TARGET_CHARS = 800

# предел длины письма, которое разбирается как просьба о свёртке. просьба
# занимает строку-две; текст длиннее — это письмо по делу, в котором слово
# «переписка» стоит рядом со словом «итог», и свёртка по нему стёрла бы
# контекст против воли пользователя
MAX_REQUEST_CHARS = 400

# явная команда в начале письма: разбирается независимо от длины остального
# текста и от вложений
_COMMAND = re.compile(r"^\s*/(summary|сводка|суммаризация|суммаризируй)\b", re.IGNORECASE)

# просьба словами: нужны оба признака сразу — действие и его предмет.
# одного действия мало, «подведи итог» относится и к вложенному документу.
#
# действие опознаётся по глагольной форме, а не по существительному: «сводка»
# сама по себе встречается в письме, которым пользователь отвечает на сводку
# («спасибо, хорошая сводка, а что по срокам обсуждения?»), и свёртка по нему
# стёрла бы контекст вместо ответа на вопрос. существительное принимается
# только вместе с глаголом — «сделай сводку», «нужна сводка»
_ACTION = re.compile(
    r"(суммаризир\w*|суммаризац\w+|резюмир\w*|сверни\w*|подведи\s+итог\w*|"
    r"(сделай|составь|собери|нужна|нужно|дай)\s+(краткую\s+|общую\s+|короткую\s+)?"
    r"(сводк\w+|саммари|резюме|итог\w*))",
    re.IGNORECASE,
)
_OBJECT = re.compile(r"(переписк\w+|сесси\w+|диалог\w*|тред\w*|разговор\w*|бесед\w+|обсужден\w+|контекст\w*)", re.IGNORECASE)

# шаблон запроса на суммаризацию. требования пронумерованы: модель держит
# короткий нумерованный список надёжнее связного абзаца.
# пункт про авторов обязателен — сводка без указания, кто что написал,
# превращает диалог в изложение от неизвестного лица, и следующий ответ модели
# приписывает вопросы пользователя себе.
# время писем в сводку не идёт: в контексте оно ничего не решает, а место
# занимает
_INSTRUCTION = """Сверни переписку ниже в одну сводку. Она заменит собой эти письма в контексте диалога.

Требования к сводке:
1. Указывай автора каждой мысли: «{peer}» — то, что написал пользователь, «{me}» — то, что ответила модель.
2. Сохрани суть: заданные вопросы, полученные ответы, решения, числа, названия, договорённости и открытые вопросы.
3. Время отправки писем не указывай.
4. Не отвечай на вопросы из переписки и не добавляй ничего от себя.
5. Уложись примерно в {target} символов.

В ответе — только текст сводки, без вступления и заголовка.

Тема переписки: {title}

--- переписка ---
{transcript}
--- конец переписки ---"""

# подпись строки в стенограмме: кто кому написал. форма «А → Б» задана прямо,
# потому что то же требование предъявляется к сводке
_FROM_USER = "{peer} → {me}:"
_FROM_MODEL = "{me} → {peer}:"
_FROM_SUMMARY = "Сводка более ранней переписки:"


# вход: текст письма пользователя.
# выход: True, если письмо просит свернуть переписку.
# разбор идёт по двум путям: команда /summary в начале письма и просьба
# словами. просьба словами требует и действия, и предмета, и короткого письма —
# ложное срабатывание стирает контекст сессии, и цена ошибки здесь выше цены
# нераспознанной просьбы: её пользователь повторит командой
def is_summary_request(text: str) -> bool:
    """Определяет, просит ли письмо свернуть переписку в сводку."""
    if not text or not SUMMARY_ENABLED:
        return False

    if _COMMAND.match(text):
        return True

    # длинное письмо командой не считается
    if len(text) > MAX_REQUEST_CHARS:
        return False

    return bool(_ACTION.search(text) and _OBJECT.search(text))


# вход: идентификатор сессии.
# выход: контекст сессии целиком: сводка, если она есть, и все реплики после неё.
#
# свёртка читает историю сама и никогда не берёт её у вызывающего кода:
# pipeline и cli читают историю с ограничением MAX_HISTORY_MESSAGES, то есть
# получают только последние реплики. сводка, снятая с такого окна, покрыла бы
# границей covers_upto и те реплики, которые в неё не вошли, — они исчезли бы
# из контекста, не попав ни в одну сводку
def full_context(session_id: int) -> List[Dict[str, Any]]:
    """Читает контекст сессии целиком — то, что подлежит свёртке."""
    return storage.get_history(session_id)


# вход: контекст сессии от storage.get_history.
# выход: суммарная длина строк контекста в символах.
# считается только текст реплик: служебные поля в запрос не уходят
def context_chars(history: Sequence) -> int:
    """Считает объём контекста сессии в символах."""
    return sum(len(row["body"]) for row in history)


# вход: контекст сессии и текст текущего запроса (письмо вместе с блоком
# описаний вложений — см. docstring fit_session).
# выход: True, когда сессия вместе с запросом переросла SESSION_MAX_CHARS.
# текущий запрос входит в расчёт, но в свёртку не попадает: свёртка покрывает
# реплики, предшествующие ему, и ответ на него собирается уже по сводке
def over_limit(history: Sequence, prompt: str) -> bool:
    """Сообщает, дошла ли сессия до предела, за которым нужна свёртка."""
    if not SUMMARY_ENABLED or SESSION_MAX_CHARS <= 0:
        return False

    # свернуть можно то, что состоит больше чем из одной строки: сессия
    # из единственной сводки после повторной свёртки короче не станет
    if len(history) < 2:
        return False

    return context_chars(history) + len(prompt) > SESSION_MAX_CHARS


# вход: объём свёртываемой переписки в символах.
# выход: целевая длина сводки в символах.
# доля задаётся SUMMARY_COMPRESSION_RATIO. нижняя граница MIN_TARGET_CHARS
# защищает короткую переписку, верхняя — половина предела сессии — держит
# сводку такой, чтобы после свёртки оставался запас на новые письма
def target_chars(source_chars: int) -> int:
    """Считает целевую длину сводки по коэффициенту сжатия."""
    ceiling = max(MIN_TARGET_CHARS, SESSION_MAX_CHARS // 2)
    return max(MIN_TARGET_CHARS, min(int(source_chars * SUMMARY_COMPRESSION_RATIO), ceiling))


# вход: контекст сессии и адрес собеседника.
# выход: стенограмма переписки: подпись автора, затем текст реплики.
# подпись обязательна: в запрос переписка уходит одним текстом, и без неё
# вопросы пользователя неотличимы от ответов модели
def transcript(history: Sequence, peer_email: str) -> str:
    """Собирает переписку в текст с указанием автора каждой реплики."""
    peer = f"Пользователь ({peer_email})" if peer_email else "Пользователь"
    parts = []

    for row in history:
        body = row["body"].strip()

        if row["role"] == SUMMARY_ROLE:
            label = _FROM_SUMMARY
        elif row["role"] == "assistant":
            label = _FROM_MODEL.format(me=MAIL_DISPLAY_NAME, peer=peer)

            # метка [Sofi] снимается только здесь: автора называет подпись
            # строки, и второе указание на него занимало бы место в запросе.
            # у реплики пользователя та же строка означала бы цитату, которую
            # он вставил руками, и её удаление исказило бы его письмо
            if body.startswith(REPLY_MARKER):
                body = body[len(REPLY_MARKER):].lstrip()
        else:
            label = _FROM_USER.format(me=MAIL_DISPLAY_NAME, peer=peer)

        parts.append(f"{label}\n{body}")

    # пустая строка между репликами: без неё модель склеивает соседние письма
    return "\n\n".join(parts)


# вход: контекст сессии, тема сессии и адрес собеседника.
# выход: текст сводки.
# побочный эффект: запрос к модели через llm.generate.
# история в запрос не передаётся: переписка уходит текстом внутри промпта,
# иначе модель продолжила бы диалог вместо его пересказа
def summarize(history: Sequence, title: str, peer_email: str) -> str:
    """Просит модель свернуть переписку сессии в сводку."""
    source_chars = context_chars(history)

    prompt = _INSTRUCTION.format(
        peer=f"Пользователь ({peer_email})" if peer_email else "Пользователь",
        me=MAIL_DISPLAY_NAME,
        target=target_chars(source_chars),
        title=title,
        transcript=transcript(history, peer_email),
    )

    text = llm.generate([], prompt).strip()

    # сводка длиннее исходной переписки означает, что модель пересказала письма
    # подробнее оригинала. текст всё равно принимается: он заменяет реплики,
    # и следующая свёртка пойдёт уже от него, а отказ оставил бы сессию
    # за пределом и запускал бы суммаризацию на каждом письме
    if len(text) >= source_chars:
        log.warning(
            "сводка (%d символов) не короче свёрнутой переписки (%d символов)",
            len(text), source_chars,
        )

    return text


# вход: текст сводки, идентификатор последней покрытой реплики и время записи.
# выход: строка контекста в той же форме, что отдаёт storage.get_history.
# нужна вызывающему коду до перечитывания базы: ответ на текущее письмо
# собирается по свёрнутому контексту сразу, без второго запроса к базе
def context_row(body: str, covers_upto: int, created_at: str = "") -> Dict[str, Any]:
    """Приводит сводку к форме строки контекста сессии."""
    return {
        "id": covers_upto,
        "role": SUMMARY_ROLE,
        "body": body,
        "body_raw": None,
        "created_at": created_at or storage.now(),
    }


# вход: идентификатор сессии, причина свёртки и режим примерки.
# выход: новый контекст сессии — список из одной сводки; пустой список
# у сессии без реплик.
# побочные эффекты: запрос к модели и строка в таблице summaries; в режиме
# примерки запись не выполняется.
# предусловие: вызывается под замком сессии — между чтением истории и записью
# сводки в сессию не должна попасть чужая реплика.
# граница свёртки берётся из последней строки контекста: у реплики это её
# идентификатор, у прежней сводки — граница, которую она уже покрывала
def fold(session_id: int, reason: str, dry_run: bool = False) -> List[Dict[str, Any]]:
    """Сворачивает контекст сессии в сводку и отдаёт контекст из неё одной."""
    # контекст читается здесь, а не приходит аргументом: свёртка обязана
    # покрыть всё, что осталось от прошлой сводки, а вызывающий код читает
    # историю с ограничением MAX_HISTORY_MESSAGES
    history = full_context(session_id)

    if not history:
        return []

    session = storage.get_session(session_id)
    title = session["title"] if session else ""
    peer_email = session["peer_email"] if session else ""

    covers_upto = int(history[-1]["id"])
    covers_chars = context_chars(history)

    body = summarize(history, title, peer_email)

    log.info(
        "сессия %s свёрнута (%s): %d строк, %d символов -> %d символов",
        session_id, reason, len(history), covers_chars, len(body),
    )

    if not dry_run:
        storage.add_summary(session_id, body, covers_upto, covers_chars, reason)

    return [context_row(body, covers_upto)]


# вход: идентификатор сессии, её контекст, текст текущего запроса (письмо
# вместе с блоком описаний вложений — request_prompt из pipeline._answer,
# а не только тело письма) и режим примерки.
# выход: контекст для запроса — прежний либо свёрнутый в сводку.
# сбой суммаризации контекст не меняет: запрос уходит полным, а причина
# остаётся в логе. отказ отвечать на письмо из-за неудавшейся свёртки был бы
# для пользователя потерей ответа на вопрос, которого он не задавал
def fit_session(
    session_id: Optional[int], history: Sequence, prompt: str, dry_run: bool = False
) -> List[Dict[str, Any]]:
    """Сворачивает переписку, если сессия доросла до предела объёма."""
    rows = list(history)

    if not session_id or not over_limit(rows, prompt):
        return rows

    log.info(
        "сессия %s достигла предела %d символов: %d в истории, %d в письме с вложениями",
        session_id, SESSION_MAX_CHARS, context_chars(rows), len(prompt),
    )

    try:
        return fold(session_id, REASON_LIMIT, dry_run) or rows
    except Exception as exc:
        log.error("свёртка сессии %s не удалась, запрос уходит целиком: %s", session_id, exc)
        return rows
