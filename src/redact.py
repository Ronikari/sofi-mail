"""Маскирование персональных данных в логах.

Лог демона уходит в journald, а оттуда обычно в систему сбора логов, где круг
читателей шире круга допущенных к переписке. При этом сами данные в логе не
нужны: чтобы разобрать инцидент, достаточно понимать, *какой* адрес и *какое*
письмо, а не кто и о чём пишет.

Поэтому адрес маскируется до вида `b***@company.ru` — домен остаётся (по нему
видно внутренний отправитель или внешний), локальная часть скрыта. Тема письма
не маскируется, а заменяется целиком: она содержательна сама по себе
(«Re: сокращение отдела продаж»), и частичный показ ничего не спасает.

`LOG_PII=true` возвращает прежнее поведение — на время разбора конкретной
проблемы, когда нужно сопоставить лог с конкретным письмом.
"""

from src.config import LOG_PII


def email_addr(address: str) -> str:
    """Адрес для лога: `ivanov@company.ru` -> `i***@company.ru`."""
    if LOG_PII:
        return address or "?"
    if not address:
        return "?"
    local, _, domain = address.partition("@")
    if not domain:
        return "***"
    return f"{local[:1]}***@{domain}"


def subject(text: str) -> str:
    """Тема письма для лога: содержимое не раскрывается вовсе."""
    if LOG_PII:
        return text or "(без темы)"
    return f"(тема скрыта, {len(text)} симв.)" if text else "(без темы)"
