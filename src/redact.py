# Маскирование ПДн в логах: лог демона уходит в journald и общую систему сбора логов,
# круг читателей которой шире круга допущенных к переписке. Управляется флагом LOG_PII.

from src.config import LOG_PII


# вход: адрес в форме local@domain, пустая строка допустима.
# выход: строка для лога, доменная часть сохраняется целиком.
def email_addr(address: str) -> str:
    """Заменяет локальную часть адреса первым символом и звёздочками."""
    # LOG_PII=true отдаёт адрес без изменений: режим разбора инцидента, когда
    # строку лога требуется сопоставить с конкретным письмом
    if LOG_PII:
        return address or "?"

    # пустое значение приходит из письма без заголовка From
    if not address:
        return "?"

    # partition делит строку по первому @; domain пуст при отсутствии разделителя
    local, _, domain = address.partition("@")

    # значение без @ скрывается целиком: доменной части в нём нет
    if not domain:
        return "***"

    # домен остаётся открытым: по нему определяется принадлежность отправителя
    # к домену компании
    return f"{local[:1]}***@{domain}"


# вход: тема письма, пустая строка допустима.
# выход: строка для лога, символы темы в неё не попадают.
def subject(text: str) -> str:
    """Заменяет тему письма отметкой о её длине."""
    # LOG_PII=true отдаёт тему без изменений, режим тот же, что в email_addr
    if LOG_PII:
        return text or "(без темы)"

    # тема письма несёт смысл целиком («Re: сокращение отдела продаж»), поэтому
    # частичный показ раскрывает содержание; в лог уходит длина в символах
    return f"(тема скрыта, {len(text)} симв.)" if text else "(без темы)"
