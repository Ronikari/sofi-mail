# --- Телеметрия LangChain: выключена принудительно ---------------------------
# load_dotenv выше заливает содержимое .env в окружение процесса, а LangChain
# читает эти переменные напрямую. строка LANGCHAIN_TRACING_V2=true в .env,
# в юните systemd или в профиле пользователя отправляет каждый промпт вместе
# с историей переписки в облако LangSmith. для переписки должностных лиц это
# передача данных за периметр компании.
# значения выставляются присваиванием: setdefault оставил бы возможность задать
# их из окружения.
# блок стоит до первого импорта langchain — config импортируется раньше
# llm_backend, и клиент читает окружение на импорте
for _telemetry_var in (
    "LANGCHAIN_TRACING_V2",
    "LANGCHAIN_TRACING",
    "LANGSMITH_TRACING",
    "LANGCHAIN_WANDB_TRACING",
):
    os.environ[_telemetry_var] = "false"

# ключи и адрес сборщика удаляются целиком: при пустом значении клиент
# LangSmith пропускает отправку
for _telemetry_var in ("LANGCHAIN_API_KEY", "LANGSMITH_API_KEY", "LANGCHAIN_ENDPOINT"):
    os.environ.pop(_telemetry_var, None)

# корень проекта. относительные пути из .env отсчитываются от него: запуск
# `python -m src.cli` из другого каталога создал бы вторую пустую базу
PROJECT_ROOT = Path(__file__).resolve().parent.parent


# вход: имя переменной окружения и значение по умолчанию.
# выход: True для написаний 1, true, yes, on в любом регистре; False для
# остальных значений
def _bool(name: str, default: bool) -> bool:
    """Читает переменную окружения как булев флаг."""
    return os.getenv(name, str(default)).strip().lower() in ("1", "true", "yes", "on")


# вход: имя переменной окружения и путь по умолчанию.
# выход: абсолютный путь; относительное значение достраивается от PROJECT_ROOT
def _path(name: str, default: str) -> Path:
    """Читает переменную окружения как путь файловой системы."""
    raw = Path(os.getenv(name, default))
    return raw if raw.is_absolute() else PROJECT_ROOT / raw


