# сборка контекста для запроса к модели и разбор её ответа.
# порядок: контекст сессии и текст письма -> подгонка под бюджет запроса
# (fit_context) -> список сообщений langchain -> вызов шлюза -> удаление
# блоков рассуждений -> проверка ответа на пустоту.
# вход: контекст сессии от storage.get_history (реплики и сводка) и текст
# входящего письма; ссылки на загруженные документы приходят
# из owui_files.reference.
# выход: текст ответа модели; при пустом ответе поднимается RuntimeError.
# MAX_CONTEXT_CHARS и LLM_MODEL импортируются из config.py, сам запрос
# выполняет llm_backend.py.
# вызывается из pipeline.py и cli.py (команды ask и check).
#
# системный промпт в этом модуле отсутствует: промпт, параметры генерации,
# базы знаний и фильтры заданы на модели sofi-mail в рабочем пространстве
# Open WebUI. промпт, переданный в запросе, перекрывает часть правил модели

import logging
import re
from typing import Any, Dict, List, Sequence

from langchain_core.messages import AIMessage, BaseMessage, HumanMessage

from src.config import LLM_MODEL, MAX_CONTEXT_CHARS
from src.llm_backend import get_backend
from src.storage import SUMMARY_ROLE

log = logging.getLogger(__name__)

# Отсечение рассуждений. Open WebUI отдаёт их отдельным полем, если модель
# развёрнута с разбором рассуждений; если нет — теги приходят прямо в content,
# и рассуждения уехали бы пользователю письмом.
_THINK_BLOCK = re.compile(r"<think>.*?</think>", re.DOTALL | re.IGNORECASE)

# шапка сводки в запросе. сводка уходит репликой пользователя, а не системным
# сообщением: системный промпт задан на модели sofi-mail в Open WebUI, и своё
# системное сообщение перекрыло бы его правила.
# вторая фраза относится к почтовому клиенту: свёрнутые письма остаются
# в цепочке треда и приезжают цитатой в следующем письме, поэтому модель
# получает прямое указание опираться на сводку, а не на цитату
SUMMARY_PREFIX = (
    "Сводка предыдущей переписки этой сессии. Письма, вошедшие в сводку, "
    "в контекст больше не входят: если в новом письме процитированы более "
    "ранние сообщения, опирайся на сводку, а не на цитату.\n\n"
)


# вход: строка контекста сессии от storage.get_history.
# выход: сообщение langchain.
# роль assistant даёт AIMessage, роль сводки — реплику пользователя с шапкой,
# остальные значения — обычную реплику пользователя
def _as_message(row) -> BaseMessage:
    """Переводит строку контекста сессии в сообщение langchain."""
    if row["role"] == "assistant":
        return AIMessage(content=row["body"])

    if row["role"] == SUMMARY_ROLE:
        return HumanMessage(content=SUMMARY_PREFIX + row["body"])

    return HumanMessage(content=row["body"])


# вход: history — контекст сессии от старых строк к новым; budget — сколько
# символов остаётся под него после текущего письма.
# выход: строки, которые войдут в запрос, в том же порядке.
#
# объём сессии держит свёртка в summarizer.py: по достижении SESSION_MAX_CHARS
# реплики заменяются сводкой, и контекст начинается заново от неё. эта функция
# работает последней проверкой перед отправкой и историю не режет: молчаливая
# потеря реплик здесь была бы неотличима для пользователя от новой сессии.
# превышение бюджета на этом шаге означает, что письмо вместе с описаниями
# документов заняло почти весь порог, либо свёртка выключена флагом
# SUMMARY_ENABLED=false
def fit_context(history: Sequence, budget: int) -> List:
    """Готовит контекст сессии под бюджет запроса; отдаёт его целиком."""
    # копия в список: аргумент допускает тип курсора бд с одним проходом
    rows = list(history)

    total = sum(len(row["body"]) for row in rows)

    # превышение бюджета пишется в лог: по этой записи видно, что свёртка
    # до сессии не дошла, и запрос ушёл на сервер во весь размер
    if total > budget:
        log.warning(
            "контекст сессии (%d строк, %d символов) выходит за бюджет %d символов; "
            "запрос уходит целиком",
            len(rows), total, budget,
        )

    return rows


# вход: history — контекст сессии от storage.get_history, от старых строк
# к новым; prompt — текст входящего письма.
# выход: список сообщений langchain; текущее письмо занимает последнюю позицию.
# побочные эффекты отсутствуют, аргумент history остаётся неизменным
def build_messages(history: Sequence, prompt: str) -> List[BaseMessage]:
    """Собирает контекст запроса из истории сессии и текущего письма."""
    # бюджет для истории: порог символов за вычетом длины текущего письма.
    # текущее письмо входит в запрос при любом размере истории, без него
    # в запросе отсутствует вопрос пользователя.
    #
    # max(0, ...) нужен потому, что prompt приходит из pipeline уже вместе
    # с блоком описаний документов и перерастает порог при нескольких больших
    # вложениях
    budget = max(0, MAX_CONTEXT_CHARS - len(prompt))

    # одно письмо длиннее всего порога: истории бюджета не остаётся вовсе.
    # запись в лог называет причину, которую иначе пришлось бы искать
    # по ответам модели
    if len(prompt) >= MAX_CONTEXT_CHARS:
        log.warning(
            "запрос длиной %d символов достиг порога %d: бюджета под историю не осталось",
            len(prompt), MAX_CONTEXT_CHARS,
        )

    rows = fit_context(history, budget)

    # роль строки переводится в класс сообщения langchain
    kept: List[BaseMessage] = [_as_message(row) for row in rows]

    # текущее письмо занимает последнюю позицию
    return [*kept, HumanMessage(content=prompt)]


# вход: history и prompt в том же виде, что у build_messages; files — ссылки
# на документы, загруженные в Open WebUI функцией owui_files.reference.
# выход: текст ответа модели без блоков рассуждений.
# текст документов через этот модуль не проходит, он остаётся в Open WebUI.
# побочный эффект: http-запрос к Open WebUI через llm_backend.py
def generate(
    history: Sequence, prompt: str, files: Sequence[Dict[str, Any]] = ()
) -> str:
    """Возвращает ответ модели на письмо с учётом истории сессии и вложений."""
    messages = build_messages(history, prompt)

    log.debug(
        "запрос к %s: %d сообщений в контексте, файлов %d", LLM_MODEL, len(messages), len(files)
    )

    # блоки <think> удаляются до всех проверок: текст внутри них попал бы
    # в письмо пользователю
    text = _THINK_BLOCK.sub("", get_backend().complete(messages, files)).strip()

    # пустая строка после удаления рассуждений означает, что лимит ответа
    # израсходован моделью на рассуждения; письмо-пустышка не отправляется
    if not text:
        raise RuntimeError(
            "модель вернула пустой ответ (вероятно, лимит ответа на модели "
            "sofi-mail в Open WebUI израсходован на рассуждения)"
        )
    return text


# выход: строка с адресом шлюза и именем модели.
# поднимает RuntimeError при недоступности сервера, отказе по ключу
# и отсутствии LLM_MODEL в списке моделей
def check_llm() -> str:
    """Отдаёт строку о доступности Open WebUI для команды check."""
    return get_backend().describe()
